
import SwiftUI

extension Font {

    static func avenirRegular(size: CGFloat) -> Font {
        return Font.custom("AvenirNext-Regular", size: size)
    }

    static func avenirMedium(size: CGFloat) -> Font {
        return Font.custom("AvenirNext-Medium", size: size)
    }

    static func avenirDemiBold(size: CGFloat) -> Font {
        return Font.custom("AvenirNext-DemiBold", size: size)
    }

    static func avenirBold(size: CGFloat) -> Font {
        return Font.custom("AvenirNext-Bold", size: size)
    }
}

